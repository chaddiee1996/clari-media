"""Builds the 'How to post.txt' guide for the stories zip from stories.json."""
import json, sys, pathlib

out = pathlib.Path(sys.argv[1])
stories = json.loads((out / "stories.json").read_text())
anim = set(sys.argv[2:])

lines = []
A = lines.append
A("CLARI STORIES FOR NOVEMBER 2026")
A("=" * 33)
A("")
A("Each file is named with the day and time to post it, for example \"04-11-26 - 7pm\".")
A("(iPhone file names can't contain \"/\", so the dates use dashes.)")
A("")
A("HOW TO POST ONE")
A("1. Save the file to your Photos (open it in Files, tap Share, then Save Image or Save Video).")
A("2. In Instagram, swipe right from the home feed to open the story camera.")
A("3. Pick the image or video from your camera roll.")
A("4. Add the sticker listed below for that day (tap the sticker icon at the top, a square smiley face).")
A("5. Put the sticker in the empty space the design leaves for it. Keep it away from the very top and very bottom.")
A("6. Tap Your story.")
A("7. If the list below says a highlight, open the story after posting, tap Highlight (the heart at the bottom), and pick that highlight.")
A("")
A("Link stickers use clariapp.co, which sends people to the right store. Check it on your phone once before the first one.")
A("")
A("THE STORIES")
A("-" * 11)
for s in stories:
    ext = ".mp4" if s["name"] in anim else ".png"
    A("")
    A(f"{s['name']}   ({s['name'] + ext})")
    A(f"  Sticker: {s['sticker']}")
    A(f"  Highlight: {s['highlight'] or 'none, it is only useful on the day'}")

A("")
A("")
A("HIGHLIGHTS")
A("-" * 10)
A("Create these six, in this order from left to right on your profile:")
A("  1. Start here    the four images in the 'highlights' folder (Start here 1 to 4), plus the 28 Nov story")
A("  2. Symptoms      4, 6, 7, 10, 13 and 26 Nov stories")
A("  3. GP visits     19, 22 and 24 Nov stories")
A("  4. Myths         11, 22 and 24 Nov stories")
A("  5. Self care     16 and 17 Nov stories")
A("  6. New in Clari  8 Nov story (add future app updates here)")
A("")
A("Post the four Start here images as stories first. Do it on 4 Nov, an hour or so before the 7pm poll, one after the other.")
A("Then add them to a new highlight called Start here.")
A("")
A("To make a new highlight: open your profile, tap New (the + under your bio), pick the stories, tap Next, type the name, tap Add.")
A("")
A("HIGHLIGHT COVERS")
A("Save the six images in the 'covers' folder to your Photos.")
A("For each highlight: open your profile, press and hold the highlight, tap Edit highlight, tap Edit cover,")
A("tap the photo icon, pick the matching cover, centre it so the circle is in the middle, then tap Done.")
A("")
A("Names are kept short so they show in full under each circle on a phone.")
A("")
A("OPTIONAL: SHARING FEED POSTS")
A("The 11, 17, 20 and 26 Nov stories show the post and need a link sticker.")
A("To get a post's link: open the post, tap the three dots, then Copy link.")
A("Post those stories about an hour after the post goes live.")

(out / "How to post.txt").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
